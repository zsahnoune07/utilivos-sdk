import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

type ModeTokens = Record<string, string>;

type ScaleRole = {
  size: number;
  weight: number;
};

type ThemeTokens = {
  design_system_version: number;
  source?: Record<string, string>;
  colors: {
    light: ModeTokens;
    dark: ModeTokens;
  };
  spacing: number[];
  radius: Record<string, number>;
  elevation: Record<string, string>;
  typography: {
    fontFamily: string;
    headline: Record<string, ScaleRole>;
    body: Record<string, ScaleRole>;
    label: Record<string, ScaleRole>;
  };
};

const sdkRoot = resolve(__dirname, '..');
const tokenPath = resolve(
  process.argv[2] ?? resolve(sdkRoot, '..', 'docs', 'design-system', 'tokens.json'),
);
const outputPath = resolve(
  process.argv[3] ?? resolve(sdkRoot, 'ui', 'base.css'),
);

const tokens = JSON.parse(readFileSync(tokenPath, 'utf8')) as ThemeTokens;

function writeModeVariables(mode: 'light' | 'dark', values: ModeTokens): string[] {
  const lines: string[] = [];
  const selector = mode === 'light' ? ':root {' : ':root[data-uv-theme="dark"] {';
  lines.push(selector);
  for (const [name, value] of Object.entries(values)) {
    lines.push(`  --uv-color-${toKebab(name)}: ${value};`);
  }
  if (mode === 'dark') {
    lines.push('  color-scheme: dark;');
  }
  lines.push('}');
  return lines;
}

function buildCSS(): string {
  const lines: string[] = [];
  lines.push('/* Generated by utilivo-sdk/theme/generate-web-theme.ts. */');
  lines.push('/* Source: docs/design-system/tokens.json */');
  lines.push('');

  lines.push(':root {');
  lines.push('  color-scheme: light dark;');
  lines.push(`  --uv-font-family: ${tokens.typography.fontFamily};`);

  for (const [name, value] of Object.entries(tokens.radius)) {
    lines.push(`  --uv-radius-${toKebab(name)}: ${value}px;`);
  }

  tokens.spacing.forEach((value, index) => {
    lines.push(`  --uv-space-${index + 1}: ${value}px;`);
  });

  for (const [name, value] of Object.entries(tokens.elevation)) {
    lines.push(`  --uv-shadow-${toKebab(name)}: ${value};`);
  }

  emitTypographyRole(lines, 'headline', tokens.typography.headline);
  emitTypographyRole(lines, 'body', tokens.typography.body);
  emitTypographyRole(lines, 'label', tokens.typography.label);
  lines.push('');
  lines.push('  --uv-motion-fast: 120ms;');
  lines.push('  --uv-motion-normal: 220ms;');
  lines.push('  --uv-motion-slow: 360ms;');
  lines.push('  --uv-motion-emphasis: 520ms;');
  lines.push('  --uv-ease-standard: cubic-bezier(0.2, 0, 0, 1);');
  lines.push('  --uv-ease-emphasis: cubic-bezier(0.16, 1, 0.3, 1);');
  lines.push('');
  lines.push('  --uv-border-thin: 1px;');
  lines.push('  --uv-border-thick: 2px;');
  lines.push('}');
  lines.push('');

  lines.push(...writeModeVariables('light', tokens.colors.light));
  lines.push('');
  lines.push(...writeModeVariables('dark', tokens.colors.dark));
  lines.push('');
  lines.push('@media (prefers-color-scheme: dark) {');
  lines.push('  :root:not([data-uv-theme="light"]) {');
  for (const [name, value] of Object.entries(tokens.colors.dark)) {
    lines.push(`    --uv-color-${toKebab(name)}: ${value};`);
  }
  lines.push('    color-scheme: dark;');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push(':root {');
  lines.push('  --uv-surface-page: var(--uv-color-background);');
  lines.push('  --uv-surface-base: var(--uv-color-surface);');
  lines.push('  --uv-surface-raised: var(--uv-color-surface-alt);');
  lines.push('  --uv-surface-overlay: color-mix(in srgb, var(--uv-color-surface) 92%, var(--uv-color-primary) 8%);');
  lines.push('');
  lines.push('  --uv-text-primary: var(--uv-color-text);');
  lines.push('  --uv-text-secondary: var(--uv-color-muted);');
  lines.push('  --uv-text-inverse: var(--uv-color-on-primary);');
  lines.push('');
  lines.push('  --uv-border-subtle: color-mix(in srgb, var(--uv-color-outline) 36%, transparent);');
  lines.push('  --uv-border-strong: var(--uv-color-outline);');
  lines.push('  --uv-border-focus: var(--uv-color-primary);');
  lines.push('');
  lines.push('  --uv-state-hover: color-mix(in srgb, var(--uv-color-primary) 10%, transparent);');
  lines.push('  --uv-state-active: color-mix(in srgb, var(--uv-color-primary) 18%, transparent);');
  lines.push('  --uv-state-selected: color-mix(in srgb, var(--uv-color-primary) 22%, transparent);');
  lines.push('');
  lines.push('  --uv-focus-ring-width: var(--uv-border-thick);');
  lines.push('  --uv-focus-ring-color: color-mix(in srgb, var(--uv-border-focus) 60%, transparent);');
  lines.push('}');
  lines.push('');
  lines.push('* {');
  lines.push('  box-sizing: border-box;');
  lines.push('}');
  lines.push('');
  lines.push('html {');
  lines.push('  min-height: 100%;');
  lines.push('  background: var(--uv-surface-page);');
  lines.push('}');
  lines.push('');
  lines.push('html,');
  lines.push('body {');
  lines.push('  min-height: 100%;');
  lines.push('}');
  lines.push('');
  lines.push('body {');
  lines.push('  margin: 0;');
  lines.push('  min-height: 100vh;');
  lines.push('  font-family: var(--uv-font-family);');
  lines.push('  background: var(--uv-surface-page);');
  lines.push('  color: var(--uv-text-primary);');
  lines.push('  font-size: var(--uv-font-size-body-md);');
  lines.push('  font-weight: var(--uv-font-weight-body-md);');
  lines.push('  line-height: 1.5;');
  lines.push('  text-rendering: optimizeLegibility;');
  lines.push('  -webkit-font-smoothing: antialiased;');
  lines.push('}');
  lines.push('');
  lines.push('img,');
  lines.push('svg,');
  lines.push('video,');
  lines.push('canvas {');
  lines.push('  display: block;');
  lines.push('  max-width: 100%;');
  lines.push('}');
  lines.push('');
  lines.push('button,');
  lines.push('input,');
  lines.push('select,');
  lines.push('textarea {');
  lines.push('  font: inherit;');
  lines.push('  color: inherit;');
  lines.push('}');
  lines.push('');
  lines.push('a {');
  lines.push('  color: var(--uv-color-primary);');
  lines.push('}');
  lines.push('');
  lines.push(':focus-visible {');
  lines.push('  outline: var(--uv-focus-ring-width) solid var(--uv-focus-ring-color);');
  lines.push('  outline-offset: 2px;');
  lines.push('}');
  lines.push('');
  lines.push('@media (prefers-reduced-motion: reduce) {');
  lines.push('  :root {');
  lines.push('    --uv-motion-fast: 0ms;');
  lines.push('    --uv-motion-normal: 0ms;');
  lines.push('    --uv-motion-slow: 0ms;');
  lines.push('    --uv-motion-emphasis: 0ms;');
  lines.push('  }');
  lines.push('');
  lines.push('  *,');
  lines.push('  *::before,');
  lines.push('  *::after {');
  lines.push('    animation-duration: 0ms !important;');
  lines.push('    animation-iteration-count: 1 !important;');
  lines.push('    transition-duration: 0ms !important;');
  lines.push('    scroll-behavior: auto !important;');
  lines.push('  }');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

function emitTypographyRole(
  lines: string[],
  role: string,
  values: Record<string, ScaleRole>,
): void {
  for (const [name, config] of Object.entries(values)) {
    lines.push(`  --uv-font-size-${role}-${toKebab(name)}: ${config.size}px;`);
    lines.push(`  --uv-font-weight-${role}-${toKebab(name)}: ${config.weight};`);
  }
}

function toKebab(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[_\s]+/g, '-')
    .toLowerCase();
}

writeFileSync(outputPath, buildCSS(), 'utf8');
console.log(`wrote ${outputPath}`);
